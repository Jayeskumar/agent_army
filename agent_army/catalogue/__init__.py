"""The office catalogue: hundreds of specialists across every department.

Roles are defined compactly in the department modules and expanded into
full :class:`AgentSpec` objects here. Run ``python -m agent_army.catalogue``
to print the Markdown catalogue.
"""

from __future__ import annotations

from ..agent import AgentSpec
from . import business, growth, operations, people, product_tech
from ._schema import Department, Role

DEPARTMENTS: list[Department] = [
    *business.DEPARTMENTS,
    *people.DEPARTMENTS,
    *growth.DEPARTMENTS,
    *product_tech.DEPARTMENTS,
    *operations.DEPARTMENTS,
]

REGULATED_NOTE = (
    "Your work is a draft for review by a qualified professional in this field. Do not present it as "
    "professional advice, and point out where expert sign-off is required."
)
WEB_NOTE = (
    "When web research tools are available, cite the URL for every external fact you use. When they are "
    "not, say what you would need to look up instead of guessing."
)


def build_mission(role: Role, dept: Department) -> str:
    deliverables = ", ".join(f"`{d}`" for d in role.deliverables)
    parts = [
        role.mission,
        "",
        f"Deliverables: {deliverables}. Submit each one as a named artifact in your report. When you can write "
        f"files, also save each deliverable under `deliverables/{role.name}/` (Markdown for documents, CSV for "
        f"tables).",
        "Work from the material in the workspace and the context you are given. Where information is missing, "
        "state your assumptions and list open questions. Never invent facts, figures, names, quotes or sources.",
    ]
    if dept.regulated:
        parts.append(REGULATED_NOTE)
    if "web" in role.tiers:
        parts.append(WEB_NOTE)
    return "\n".join(parts)


def build_specs() -> list[AgentSpec]:
    specs: list[AgentSpec] = []
    seen: set[str] = set()
    for dept in DEPARTMENTS:
        for role in dept.parse():
            if role.name in seen:
                raise ValueError(f"Duplicate catalogue agent '{role.name}'")
            seen.add(role.name)
            specs.append(AgentSpec(
                name=role.name,
                title=role.title,
                division=dept.name,
                mission=build_mission(role, dept),
                tiers=role.tiers,
                light=dept.light,
                deliverables=role.deliverables,
            ))
    return specs


def render_markdown(core: list[AgentSpec], catalogue: list[AgentSpec]) -> str:
    total = len(core) + len(catalogue) + 1
    by_dept: dict[str, list[AgentSpec]] = {}
    for s in catalogue:
        by_dept.setdefault(s.division, []).append(s)
    lines = [
        "# Agent Army catalogue",
        "",
        "<!-- Generated by `python -m agent_army.catalogue > CATALOGUE.md`. Do not edit by hand. -->",
        "",
        f"**{total} agents**: the commander, {len(core)} core SDLC specialists and {len(catalogue)} office "
        f"specialists in {len(by_dept)} departments.",
        "",
        "Tools: `r` read files, `w` write files, `x` run allow-listed commands, `web` web research.",
        "",
        "## Departments",
        "",
        "| Department | Agents | Covers |",
        "|---|---|---|",
        f"| [Core SDLC squad](#core-sdlc-squad) | {len(core)} | Requirements to release for software teams |",
    ]
    for dept in DEPARTMENTS:
        anchor = dept.label.lower().replace(" & ", "--").replace(" ", "-").replace("&", "")
        lines.append(f"| [{dept.label}](#{anchor}) | {len(by_dept.get(dept.name, []))} | {dept.description} |")
    lines += ["", "## Core SDLC squad", "", "| Agent | Title | Division | Tools | Mission |", "|---|---|---|---|---|"]
    for s in core:
        lines.append(f"| `{s.name}` | {s.title} | {s.division} | {_tiers(s)} | {s.tagline} |")
    for dept in DEPARTMENTS:
        lines += ["", f"## {dept.label}", "", dept.description, "",
                  "| Agent | Title | Tools | Mission | Deliverables |", "|---|---|---|---|---|"]
        for s in by_dept.get(dept.name, []):
            mission = s.mission.split("\n", 1)[0].replace("|", "\\|")
            lines.append(f"| `{s.name}` | {s.title} | {_tiers(s)} | {mission} | {', '.join(s.deliverables)} |")
    return "\n".join(lines) + "\n"


def _tiers(spec: AgentSpec) -> str:
    code = "".join(c for t, c in (("read", "r"), ("write", "w"), ("exec", "x")) if t in spec.tiers)
    return code + ("+web" if "web" in spec.tiers else "")
